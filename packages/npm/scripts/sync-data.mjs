// Writes src/data.ts from dist/questions.json at the repo root.
// Run it with "make sync-packages" after "make build-data".
import { readFileSync, writeFileSync } from "node:fs";

const source = new URL("../../../dist/questions.json", import.meta.url);
const target = new URL("../src/data.ts", import.meta.url);
const json = JSON.stringify(JSON.parse(readFileSync(source, "utf8")), null, 2);

writeFileSync(
  target,
  `// Generated by scripts/sync-data.mjs from dist/questions.json. Do not edit.
import type { DatasetFile } from "./types.js";

export const embeddedFile: DatasetFile = ${json};
`,
);
